function QuestionCard({
  question,
  language,
  onSelectOption,
  selectedOption,
  isDark,
}: {
  question: Question;
  language: "en" | "ar" | "ru" | "ur" | "hi";
  onSelectOption: (optionIndex: number) => void;
  selectedOption: number[];
  isDark: boolean;
}) {
  const { theme, fontScale } = useTheme();
  const [isSpeaking, setIsSpeaking] = useState<boolean>(false);
  const handleSpeak = () => {
    if (isSpeaking) {
      Speech.stop();
      setIsSpeaking(false);
      return;
    }
    // Compose the speech string
    let speechText = getQuestionSpeech();
    function getQuestionSpeech() {
      switch (language) {
        case "en":
          return `Question: ${question.title.en}: ${question.question.en}  Options: ${question.options.map((option) => option.label.en).join(". ")}`;
        case "ru":
          return `Вопрос: ${question.title.ru}: ${question.question.ru} варианты ${question.options.map((option) => option.label.ru).join(". ")}`;
        case "ar":
          return `${question.options.map((option) => option.label.ar).join(" .")} سؤال ${question.question.ar} :${question.title.ar} الخيارات`;
        case "hi":
          return `सवाल ${question.title.hi}: ${question.question.hi}  विकल्प ${question.options.map((option) => option.label.hi).join(". ")}`;
        case "ur":
          return `${question.options.map((option) => option.label.ur).join(" .")} :اختیار ${question.question.ur} :${question.title.ur} سوال`;
        default:
          return `Question: ${question.title.en}: ${question.question.en}  Options: ${question.options.map((option) => option.label.en).join(". ")}`;
      }
    }
    setIsSpeaking(true);
    Speech.speak(speechText, {
      language: language,
      onDone: () => setIsSpeaking(false),
      onStopped: () => setIsSpeaking(false),
    });
  };

  return (
    <View
      style={{
        paddingHorizontal: 4,
        backgroundColor: theme.background,
        marginHorizontal: 10,
      }}
    >
      <TouchableOpacity onPress={handleSpeak} style={{ marginLeft: 12, position: "relative", left: 230 }}>
        <MaterialIcons
          name="volume-up"
          size={34}
          color={isSpeaking ? "#137fec" : "#64748b"}
        />
      </TouchableOpacity>
      <View>
        <Text
          style={[
            {
              fontWeight: 600,
              fontSize: 24 * fontScale,
            },
            isDark && {
              color: "#e1e2e5",
            },
          ]}
        >
          {question.title[language]}
        </Text>
        <Text
          style={[
            {
              fontWeight: 400,
              fontSize: 22 * fontScale,
            },
            isDark && {
              color: "#e1e2e5",
            },
          ]}
        >
          {question.question[language]}
        </Text>
      </View>
      <View>
        {question.options.map((option, index) => {
          const selected = selectedOption.includes(index + 1);
          return (
            <TouchableOpacity
              key={index}
              onPress={() => onSelectOption(index)}
              style={[
                {
                  paddingHorizontal: 15,
                  paddingVertical: 10,
                  borderColor: "#137fecff",
                  borderWidth: 2,
                  borderRadius: 15,
                  marginVertical: 5,
                  boxShadow: "0px 4px 6px rgba(0, 0, 0, 0.4)",
                  shadowColor: "#137fecff",
                },
                selected && {
                  backgroundColor: "#137fecff",
                },
              ]}
            >
              <Text
                style={[
                  {
                    fontWeight: 400,
                    fontSize: 24 * fontScale,
                  },
                  isDark && {
                    color: "#e1e2e5",
                  },
                ]}
              >
                {option.label[language]}
              </Text>
            </TouchableOpacity>
          );
        })}
      </View>
    </View>
  );
}
